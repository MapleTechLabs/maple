// Regenerates `src/skill-files.generated.ts` from the vendored markdown in `skill/`, so bundles
// carry the skill's text without a raw-import loader. `--check` fails when the module is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const skillDir = join(root, "skill")
const target = join(root, "src", "skill-files.generated.ts")

const files = readdirSync(skillDir)
	.filter((name) => name.endsWith(".md") && name !== "UPSTREAM.md")
	.sort()

const body = files
	.map(
		(name) => `\t${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(skillDir, name), "utf8"))},`,
	)
	.join("\n")

const generated = `// Generated by scripts/vendor-skill.ts from skill/*.md. Do not edit.\nexport const SKILL_FILES = {\n${body}\n} as const\n\nexport type SkillFileName = keyof typeof SKILL_FILES\n`

if (process.argv.includes("--check")) {
	const current = readFileSync(target, "utf8")
	if (current !== generated) {
		console.error(
			"src/skill-files.generated.ts is stale: run `bun run vendor` in packages/security-audit",
		)
		process.exit(1)
	}
} else {
	writeFileSync(target, generated)
	console.log(`wrote ${files.length} skill files`)
}
