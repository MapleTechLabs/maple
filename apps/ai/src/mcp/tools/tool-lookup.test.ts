import { describe, expect, it } from "@effect/vitest"
import type { McpToolSurface } from "@maple/domain/mcp-manifest"
import { Effect, Array as Arr, Record as Rec } from "effect"
import { MCP_TOOL_MODULES } from "../tool-modules.generated"
import { mapleToolCatalog, mapleToolCatalogFor, mapleToolTitle } from "./registry"
import { makeModuleToolLookup, mcpToolTitle } from "./tool-lookup"
import { canonicalToolName, TOOL_NAME_ALIASES } from "./tool-name-aliases"
import type { McpToolRegistrar } from "./types"

const SURFACES: ReadonlyArray<McpToolSurface> = ["mcp", "chat", "bot", "bot_anonymous", "workflow", "rpc"]

const definedBy = (entry: (typeof MCP_TOOL_MODULES)[number]) =>
	Effect.promise(entry.load).pipe(
		Effect.map((register) => {
			const names: Array<string> = []
			const registrar: McpToolRegistrar = { define: (spec) => void names.push(spec.name) }
			register(registrar)
			return names
		}),
	)

describe("MCP_TOOL_MODULES", () => {
	// Generated by `bun run --cwd apps/ai mcp:tools`; a new, renamed or moved tool fails here until rerun.
	it("names every registered tool in catalog order, then every retired alias", () => {
		expect(Arr.map(MCP_TOOL_MODULES, (entry) => entry.name)).toEqual([
			...Arr.map(mapleToolCatalog, (entry) => entry.name),
			...Rec.keys(TOOL_NAME_ALIASES),
		])
		for (const entry of MCP_TOOL_MODULES) {
			const tool = canonicalToolName(entry.name)
			const registered = mapleToolCatalog.find((candidate) => candidate.name === tool)
			expect(
				{ tool: entry.tool, title: entry.title, audience: entry.audience, readOnly: entry.readOnly },
				entry.name,
			).toEqual({
				tool,
				title: registered?.title,
				audience: registered?.audience,
				readOnly: registered?.hints.readOnly,
			})
		}
	})

	it.effect("loads, for each name, a module that registers the tool it claims", () =>
		Effect.forEach(MCP_TOOL_MODULES, (entry) =>
			Effect.map(definedBy(entry), (names) => expect(names, entry.name).toContain(entry.tool)),
		),
	)
})

describe("makeModuleToolLookup", () => {
	it.effect("defines exactly the tool a name means, the same one the full registry has", () =>
		Effect.gen(function* () {
			const lookup = yield* makeModuleToolLookup
			yield* Effect.forEach(MCP_TOOL_MODULES, (entry) =>
				Effect.gen(function* () {
					const definition = yield* lookup.find(entry.name)
					const registered = mapleToolCatalog.find((candidate) => candidate.name === entry.tool)
					expect(definition?.name, entry.name).toBe(entry.tool)
					expect(definition?.description).toBe(registered?.description)
					expect(definition?.outputSchema).toBe(registered?.outputSchema)
				}),
			)
		}),
	)

	it.effect("knows no name outside the registry, prototype keys included", () =>
		Effect.gen(function* () {
			const lookup = yield* makeModuleToolLookup
			yield* Effect.forEach(["not_a_maple_tool", "__proto__", "constructor", "toString"], (name) =>
				Effect.map(lookup.find(name), (definition) => {
					expect(definition, name).toBeUndefined()
					expect(mcpToolTitle(name)).toBeUndefined()
				}),
			)
		}),
	)

	it.effect("lists what each surface may see, as the full registry does", () =>
		Effect.gen(function* () {
			const lookup = yield* makeModuleToolLookup
			Arr.forEach(SURFACES, (surface) =>
				expect(lookup.namesFor(surface), surface).toEqual(
					Arr.map(mapleToolCatalogFor(surface), (entry) => entry.name),
				),
			)
		}),
	)

	it("titles a tool as the full registry does, and an alias not at all", () => {
		for (const entry of MCP_TOOL_MODULES) {
			expect(mcpToolTitle(entry.name), entry.name).toBe(mapleToolTitle(entry.name))
		}
	})
})
