/**
 * How Maple reads a pull request's diff, as pure rules shared by the reviewer's tools and the
 * approval decision: the kind of each file, how much of a patch `pr_file_diff` shows, and the paths
 * and sizes an approval never covers without a person.
 */
import { Array as Arr, String as Str } from "effect"
import type { PullRequestFile } from "./vcs"

export type PrChangedFileKind =
	| "source"
	| "test"
	| "generated"
	| "docs"
	| "config"
	| "infra"
	| "tooling"
	| "lockfile"

const TEST_PATH =
	/(^|\/)(__tests__|__mocks__|__evals__|tests?|spec|fixtures?)\/|\.(test|spec|e2e)\.[cm]?[jt]sx?$|_test\.(go|rs|py|rb)$|Tests?\.(swift|kt|java|cs)$/
// Snapshot and baseline files are regenerated by a test run, never written by hand.
const GENERATED_PATH =
	/\.gen\.|\.generated\.|(^|\/)generated\/|(^|\/)__generated__\/|(^|\/)__(snapshots|[a-z_]*baseline)__\/|\.snap$|\.pb\.(go|ts|js)$|_pb2\.py$|\.g\.(cs|dart)$|(^|\/)dist\/|(^|\/)build\//
// Tool output with a fixed name: bundler output directories, `wrangler types`, and bundles named
// after their content hash.
const TOOL_OUTPUT_PATH =
	/(^|\/)\.(open-)?next\/|(^|\/)worker-configuration\.d\.ts$|[-.][0-9a-f]{20,}\.(js|css)$/
/**
 * A migration tool's journal or snapshot under a `drizzle/` directory. Read by segment, not by one
 * pattern: a path is the author's to choose, and a pattern here would rescan it per segment.
 */
const isMigrationSnapshot = (path: string): boolean => {
	const segments = Str.split("/")(path)
	const name = segments.at(-1) ?? ""
	return (
		Arr.contains(segments.slice(0, -1), "drizzle") &&
		(name === "_journal.json" || Str.endsWith("snapshot.json")(name))
	)
}
// Any `*.lock`, `*.lock.json`, `*-lock.json` or `*-lock.yaml` is a resolver's output, whatever wrote it.
const LOCKFILE =
	/(\.lock(b|file)?|\.lock\.(json|ya?ml|hcl)|-lock\.(json|ya?ml))$|(^|\/)(go\.sum|Package\.resolved|npm-shrinkwrap\.json)$/
/** Build and developer tooling: never runs in production, so there is nothing to observe. */
const TOOLING_PATH =
	/(^|\/)(scripts|tools|\.husky|\.vscode|\.claude)\/|(^|\/)[^/]*(oxlint|eslint)-plugins?\/|\.config\.[cm]?[jt]s$|(^|\/)(Makefile|justfile|Taskfile\.ya?ml|mise\.toml)$/
const PROSE_EXTENSION = /\.(md|mdx|rst|txt|adoc)$/
const DOCS_PATH = /\.(md|mdx|rst|txt|adoc)$|(^|\/)docs?\//
const INFRA_PATH =
	/(^|\/)(\.github|\.gitlab|infra|terraform|k8s|kubernetes|helm|deploy)\/|\.tf$|(^|\/)(Dockerfile|docker-compose[^/]*\.ya?ml|alchemy\.run\.ts|wrangler\.(toml|jsonc?)|sst\.config\.ts|fly\.toml|Procfile)$/
const CONFIG_PATH =
	/(^|\/)(package\.json|tsconfig[^/]*\.json|\.eslintrc[^/]*|\.oxlintrc[^/]*|\.prettierrc[^/]*|biome\.json|pyproject\.toml|setup\.cfg|Cargo\.toml|go\.mod|\.editorconfig|\.gitignore|\.env[^/]*)$|(^|\/)\.[^/]+\.(json|ya?ml|toml)$/

/**
 * What kind of file a path is, for the reviewer's first cut.
 *
 * Deliberately coarse. The point is that tests, generated code, docs and lockfiles are never
 * reviewed, and that a change to infra is read for what it deploys rather than for spans.
 */
export const classifyChangedFile = (path: string): PrChangedFileKind => {
	if (LOCKFILE.test(path)) return "lockfile"
	if (GENERATED_PATH.test(path) || TOOL_OUTPUT_PATH.test(path) || isMigrationSnapshot(path))
		return "generated"
	if (TEST_PATH.test(path)) return "test"
	if (DOCS_PATH.test(path)) return "docs"
	if (TOOLING_PATH.test(path)) return "tooling"
	if (INFRA_PATH.test(path)) return "infra"
	if (CONFIG_PATH.test(path)) return "config"
	return "source"
}

/** Kinds a review reads: code, deploy and runtime config, and tests for the tests lens. */
export const PR_REVIEWED_FILE_KINDS: ReadonlySet<PrChangedFileKind> = new Set([
	"source",
	"infra",
	"config",
	"test",
])

/** Files `pr_changed_files` lists; a larger pull request's listing is cut there. */
export const PR_CHANGED_FILES_MAX_LISTED = 500
/** How much of one file's patch `pr_file_diff` shows. */
export const PR_FILE_DIFF_MAX_LINES = 1_500
export const PR_FILE_DIFF_MAX_CHARS = 60_000

const HUNK_HEADER = /^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@(.*)$/

/**
 * A unified patch with the new-side line number on every line that has one.
 *
 * Additions and context carry a number; deletions carry none, because they no longer exist and
 * GitHub will not anchor a comment on them. The reviewer cites what it sees here, so the format
 * is the contract: `<line> <marker> <code>`.
 */
export const annotatePatch = (
	patch: string,
): { readonly lines: ReadonlyArray<string>; readonly truncated: boolean } => {
	const out: Array<string> = []
	let newLine = 0
	let chars = 0
	let truncated = false
	for (const raw of Str.split("\n")(patch)) {
		if (out.length >= PR_FILE_DIFF_MAX_LINES || chars >= PR_FILE_DIFF_MAX_CHARS) {
			truncated = true
			break
		}
		const header = HUNK_HEADER.exec(raw)
		let rendered: string
		if (header !== null) {
			newLine = Number(header[3])
			rendered = `      ${raw}`
		} else if (Str.startsWith("+")(raw)) {
			rendered = `${Str.padStart(5)(String(newLine))} + ${Str.slice(1)(raw)}`
			newLine += 1
		} else if (Str.startsWith("-")(raw)) {
			rendered = `      - ${Str.slice(1)(raw)}`
		} else if (Str.startsWith("\\")(raw)) {
			rendered = `      ${raw}`
		} else {
			rendered = `${Str.padStart(5)(String(newLine))}   ${Str.startsWith(" ")(raw) ? Str.slice(1)(raw) : raw}`
			newLine += 1
		}
		out.push(rendered)
		chars += rendered.length + 1
	}
	return { lines: out, truncated }
}

/** CI definitions outside the directories {@link INFRA_PATH} names. */
const CI_CONFIG_PATH =
	/(^|\/)\.(circleci|buildkite|woodpecker)\/|(^|\/)(\.gitlab-ci\.ya?ml|\.travis\.ya?ml|\.drone\.ya?ml|azure-pipelines[^/]*\.ya?ml|bitbucket-pipelines\.ya?ml|Jenkinsfile[^/]*)$/
const CODEOWNERS_PATH = /(^|\/)CODEOWNERS$/
/** Manifests that name what gets installed or run: dependencies and scripts. */
const MANIFEST_PATH =
	/(^|\/)(package\.json|pyproject\.toml|setup\.(py|cfg)|Pipfile|(requirements|constraints)[^/]*\.txt|Gemfile|go\.mod|Cargo\.toml|pom\.xml|build\.gradle(\.kts)?|composer\.json)$/
const CONTAINER_PATH = /(^|\/)(Dockerfile[^/]*|[^/]+\.dockerfile|(docker-)?compose[^/]*\.ya?ml)$/i
const MIGRATION_PATH = /(^|\/)(migrations?|drizzle)\/|\.sql$/i
const SECRET_FILE_PATH = /(^|\/)\.env[^/]*$|\.(pem|key|p12|pfx|jks|keystore)$/i
/** What the review reads as instructions, and other agents' rule directories beside them. */
const REVIEWER_RULES_PATH = /(^|\/)(CLAUDE|AGENTS|SKILL)\.md$|(^|\/)\.(maple|claude|cursor)\//

const SENSITIVE_PATTERNS: ReadonlyArray<RegExp> = [
	CI_CONFIG_PATH,
	CODEOWNERS_PATH,
	LOCKFILE,
	MANIFEST_PATH,
	CONTAINER_PATH,
	INFRA_PATH,
	MIGRATION_PATH,
	SECRET_FILE_PATH,
	REVIEWER_RULES_PATH,
]

/** Words in a path that mark sign-in, access or secret handling. */
const SENSITIVE_WORDS: ReadonlySet<string> = new Set([
	"auth",
	"authn",
	"authz",
	"authentication",
	"authorization",
	"oauth",
	"sso",
	"saml",
	"secret",
	"secrets",
	"credential",
	"credentials",
	"password",
	"passwords",
	"token",
	"tokens",
	"permission",
	"permissions",
])

/**
 * A path's words, lower-cased: split on separators, on camelCase and after an acronym, so
 * `AuthService.ts` has `auth` and `SSOClient.ts` has `sso`.
 */
const pathWords = (path: string): ReadonlyArray<string> =>
	Arr.map(
		Arr.filter(
			Str.split(/[^A-Za-z0-9]+|(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])/)(path),
			Str.isNonEmpty,
		),
		Str.toLowerCase,
	)

/**
 * Whether a change to this path always waits for a person, whatever a review made of it: CI and
 * deploy config, `CODEOWNERS`, lockfiles and dependency manifests, containers, migrations, anything
 * named for sign-in, access or secrets, and the files the reviewer itself takes instructions from.
 */
export const isSensitivePath = (path: string): boolean =>
	Arr.some(SENSITIVE_PATTERNS, (pattern) => pattern.test(path)) ||
	Arr.some(pathWords(path), (word) => SENSITIVE_WORDS.has(word))

/** Prose by its extension alone: a file under `docs/` with any other name is not prose. */
export const isProseFile = (path: string): boolean => PROSE_EXTENSION.test(path)

/** The most a pull request may change and still be approved unread. */
export const PR_REVIEW_AUTO_APPROVE_MAX_CHANGED_LINES = 400
export const PR_REVIEW_AUTO_APPROVE_MAX_FILES = 25

/** What Maple's own read of the diff says about approving it, none of it from the model. */
export interface PrReviewDiffSignals {
	/** Files of a kind no review reads (generated, tooling, lockfiles, non-prose docs). */
	readonly unreviewedKindFiles: number
	/** Files GitHub gives no patch for (binary, or too large): no review read them. */
	readonly patchlessFiles: number
	/** Files whose patch is longer than `pr_file_diff` shows. */
	readonly truncatedPatchFiles: number
	/** The diff has more files than the reviewer was listed, or the provider cut its own listing. */
	readonly truncatedListing: boolean
	/** Changed paths under {@link isSensitivePath}, a rename's old path included. */
	readonly sensitivePaths: ReadonlyArray<string>
	readonly changedFiles: number
	/** Lines added and removed across the reviewed kinds. */
	readonly changedLines: number
}

/**
 * Whether Maple's own read of a diff leaves an approval possible: nothing unread, nothing
 * sensitive, within the size caps. The review's verdict decides the rest.
 */
export const prReviewDiffMayApprove = (signals: PrReviewDiffSignals): boolean =>
	signals.unreviewedKindFiles === 0 &&
	signals.patchlessFiles === 0 &&
	signals.truncatedPatchFiles === 0 &&
	!signals.truncatedListing &&
	signals.sensitivePaths.length === 0 &&
	signals.changedLines <= PR_REVIEW_AUTO_APPROVE_MAX_CHANGED_LINES &&
	signals.changedFiles <= PR_REVIEW_AUTO_APPROVE_MAX_FILES

/**
 * The approval signals of one diff. `isIgnored` marks the repository's ignored paths: they are
 * refused on their own, so they do not count as unread kinds or cut patches here.
 */
export const prReviewDiffSignals = (input: {
	readonly files: ReadonlyArray<PullRequestFile>
	/** The provider said its file listing is incomplete. */
	readonly truncated: boolean
	readonly isIgnored: (path: string) => boolean
}): PrReviewDiffSignals => {
	const read = Arr.filter(input.files, (file) => !input.isIgnored(file.path))
	const reviewed = Arr.filter(read, (file) => PR_REVIEWED_FILE_KINDS.has(classifyChangedFile(file.path)))
	return {
		unreviewedKindFiles: Arr.filter(
			read,
			(file) => !PR_REVIEWED_FILE_KINDS.has(classifyChangedFile(file.path)) && !isProseFile(file.path),
		).length,
		patchlessFiles: Arr.filter(read, (file) => file.patch === null).length,
		truncatedPatchFiles: Arr.filter(
			reviewed,
			(file) => file.patch !== null && annotatePatch(file.patch).truncated,
		).length,
		truncatedListing: input.truncated || input.files.length > PR_CHANGED_FILES_MAX_LISTED,
		sensitivePaths: Arr.dedupe(
			Arr.filter(
				Arr.flatMap(input.files, (file) =>
					file.previousPath === null ? [file.path] : [file.path, file.previousPath],
				),
				isSensitivePath,
			),
		),
		changedFiles: input.files.length,
		changedLines: Arr.reduce(reviewed, 0, (sum, file) => sum + file.additions + file.deletions),
	}
}
