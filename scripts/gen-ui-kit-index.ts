#!/usr/bin/env bun
/**
 * Writes packages/views/src/ui/INDEX.md: every kit module (packages/views/src/ui and each app's page/kit)
 * with its exports and the first line of its doc comment, so an agent reads one file to find the
 * component before it builds one. `--check` fails when the file is stale (CI).
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"
import { Array as Arr, String as Str } from "effect"

const root = join(import.meta.dir, "..")
const indexFile = join(root, "packages/views/src/ui/INDEX.md")
const KIT_ROOTS = ["packages/views/src/ui", "apps/web/src/page/kit", "apps/local-ui/src/page/kit"]

// TEA plumbing every stateful component exports; listed once as "stateful", not per name.
const PLUMBING = new Set(["init", "update", "subscriptions"])

function* walk(dir: string): Generator<string> {
	for (const entry of readdirSync(dir).sort()) {
		const path = join(dir, entry)
		if (statSync(path).isDirectory()) yield* walk(path)
		else if (Str.endsWith(".ts")(entry) && !/\.(test|generated)\.ts$/.test(entry)) yield path
	}
}

/** The first sentence of a comment block, flattened to one line. */
const firstSentence = (comment: string) => {
	const text = Arr.join(
		Arr.filter(
			Arr.map(Str.split("\n")(Str.replace(/^\/\*\*?|\*\/$/g, "")(comment)), (line) =>
				Str.trim(Str.replace(/^\s*(\*|\/\/)\s?/, "")(line)),
			),
			(line) => line !== "" && !Str.startsWith("@")(line),
		),
		" ",
	)
	const end = text.search(/\.(\s|$)/)
	const sentence = Str.replaceAll("—", ",")(end === -1 ? text : Str.slice(0, end + 1)(text))
	return sentence.length > 180 ? `${Str.trimEnd(Str.slice(0, 177)(sentence))}...` : sentence
}

const describe = (source: string) => {
	const beforeExports = Str.slice(0, Math.max(source.search(/^export /m), 0))(source)
	const header = beforeExports.match(/(?:^\/\*\*[\s\S]*?\*\/|(?:^\/\/.*\n)+)/m)?.[0]
	if (header !== undefined) return firstSentence(header)
	const docOnExport = source.match(
		/(\/\*\*(?:(?!\*\/)[\s\S])*\*\/)\s*\nexport (?:const|function) [a-z]/,
	)?.[1]
	return docOnExport === undefined ? "" : firstSentence(docOnExport)
}

const lines: string[] = []
for (const kitRoot of KIT_ROOTS) {
	lines.push("", `## ${kitRoot}`, "")
	for (const file of walk(join(root, kitRoot))) {
		const source = readFileSync(file, "utf8")
		const exports = Arr.map(
			[...source.matchAll(/^export (?:const|function) ([a-z][A-Za-z0-9]*)/gm)],
			(m) => m[1],
		)
		const stateful = exports.includes("update")
		const names = Arr.filter(exports, (name) => !PLUMBING.has(name))
		if (names.length === 0 && !stateful) continue
		const description = describe(source)
		const parts = [
			`\`${relative(root, file)}\``,
			Arr.join(
				Arr.map(names, (name) => `\`${name}\``),
				", ",
			),
			...(stateful ? ["(stateful: Model, init, update)"] : []),
		]
		lines.push(`- ${Arr.join(parts, " ")}${description === "" ? "" : `: ${description}`}`)
	}
}

const content = `# Dashboard kit index

Generated by \`bun run ui:index\` from ${Arr.join(
	Arr.map(KIT_ROOTS, (kitRoot) => `\`${kitRoot}\``),
	", ",
)}; do not edit.
Find the component here before building one. If nothing fits, build it in the kit and move the
existing copies onto it (see \`apps/web/CLAUDE.md\`).
${Arr.join(lines, "\n")}
`

if (process.argv.includes("--check")) {
	if (readFileSync(indexFile, "utf8") !== content) {
		console.error("packages/views/src/ui/INDEX.md is stale. Run `bun run ui:index` and commit it.")
		process.exit(1)
	}
} else {
	writeFileSync(indexFile, content)
}
