import { readdirSync, readFileSync, statSync } from "node:fs"
import { join, relative } from "node:path"
import { Effect, Schema } from "effect"
import { describe, expect, it } from "vitest"
import { lockfileKindOf, parseLockfile, type ParsedLockfile } from "./index.ts"

const ROOT = join(import.meta.dirname, "__fixtures__")

const decodeIds = Schema.decodeUnknownSync(Schema.fromJsonString(Schema.Array(Schema.String)))

const filesUnder = (dir: string): ReadonlyArray<string> =>
	readdirSync(dir).flatMap((name) => {
		const path = join(dir, name)
		return statSync(path).isDirectory() ? filesUnder(path) : [path]
	})

interface Fixture {
	readonly name: string
	readonly lockfile: string
	readonly manifests: ReadonlyMap<string, string>
	readonly expected: ReadonlyArray<string>
}

const fixtures: ReadonlyArray<Fixture> = readdirSync(ROOT).flatMap((kind) =>
	readdirSync(join(ROOT, kind)).flatMap((variant) => {
		const dir = join(ROOT, kind, variant)
		const files = filesUnder(dir).map((path) => relative(dir, path))
		const lockfile = files.find((file) => !file.includes("/") && lockfileKindOf(file) !== undefined)
		if (lockfile === undefined) return []
		const manifests = new Map(
			files
				.filter((f) => f.endsWith("package.json"))
				.map((f): readonly [string, string] => [f, readFileSync(join(dir, f), "utf8")]),
		)
		const expected = decodeIds(readFileSync(join(dir, "expected.json"), "utf8"))
		return [{ name: `${kind}/${variant}`, lockfile: join(dir, lockfile), manifests, expected }]
	}),
)

const parseFixture = (fixture: Fixture, withManifests = true): Promise<ParsedLockfile> =>
	Effect.runPromise(
		parseLockfile({
			path: fixture.lockfile,
			content: readFileSync(fixture.lockfile, "utf8"),
			manifests: withManifests ? fixture.manifests : undefined,
		}),
	)

const ids = (parsed: ParsedLockfile): ReadonlyArray<string> =>
	parsed.packages.map((p) => `${p.name}@${p.version}`).sort()

const relationOf = (parsed: ParsedLockfile, name: string) =>
	parsed.packages.filter((p) => p.name === name).map((p) => p.relation)

describe("fixtures generated by the real package managers", () => {
	it("covers every lockfile format but bun.lockb", () => {
		expect(new Set(fixtures.map((f) => f.name.split("/")[0]))).toEqual(
			new Set([
				"package-lock",
				"pnpm-lock",
				"yarn-v1",
				"yarn-berry",
				"bun-lock",
				"go-mod",
				"go-sum",
				"cargo-lock",
			]),
		)
	})

	it.each(fixtures.filter((f) => f.name !== "go-sum/basic"))(
		"$name matches the tool's own package list",
		async (fixture) => {
			expect(ids(await parseFixture(fixture))).toEqual([...fixture.expected].sort())
		},
	)
})

const fixture = (name: string): Fixture => {
	const found = fixtures.find((f) => f.name === name)
	if (found === undefined) return expect.unreachable(`missing fixture ${name}`)
	return found
}

const readJson = (name: string, file: string): ReadonlyArray<string> =>
	decodeIds(readFileSync(join(ROOT, name, file), "utf8"))

describe("Go fixtures", () => {
	// go list -m all walks the whole module graph, including test-only deps of deps that go.mod never pins.
	it("go.mod modules are a subset of the full module graph", async () => {
		const parsed = ids(await parseFixture(fixture("go-mod/basic")))
		expect(readJson("go-mod/basic", "module-graph.json")).toEqual(expect.arrayContaining([...parsed]))
	})

	// go.sum keeps zip hashes only for modules whose code was downloaded, all of them in the graph.
	it("go.sum modules are a subset of the module graph and a superset of go.mod", async () => {
		const sum = await parseFixture(fixture("go-sum/basic"))
		const mod = ids(await parseFixture(fixture("go-mod/basic"))).filter(
			(id) => !id.startsWith("golang.org/x/text@"),
		)
		expect(fixture("go-sum/basic").expected).toEqual(expect.arrayContaining([...ids(sum)]))
		expect(ids(sum)).toEqual(expect.arrayContaining(mod))
		expect(new Set(sum.packages.map((p) => p.relation))).toEqual(new Set(["unknown"]))
		expect(sum.warnings).toHaveLength(1)
	})

	it("marks requires direct unless commented indirect and applies replace", async () => {
		const parsed = await parseFixture(fixture("go-mod/basic"))
		expect(relationOf(parsed, "github.com/gin-gonic/gin")).toEqual(["direct"])
		expect(relationOf(parsed, "golang.org/x/net")).toEqual(["direct"])
		expect(relationOf(parsed, "golang.org/x/crypto")).toEqual(["transitive"])
		expect(parsed.packages.filter((p) => p.name === "golang.org/x/text").map((p) => p.version)).toEqual([
			"v0.8.0",
		])
	})
})

const APP_FIXTURES = [
	"package-lock/v1",
	"package-lock/v2",
	"package-lock/v3",
	"pnpm-lock/v5",
	"pnpm-lock/v6",
	"pnpm-lock/v9",
	"yarn-v1/basic",
	"yarn-berry/basic",
	"bun-lock/basic",
]
const WORKSPACE_FIXTURES = ["package-lock/workspace", "pnpm-lock/workspace", "bun-lock/workspace"]

describe("npm relations", () => {
	it.each([...APP_FIXTURES, ...WORKSPACE_FIXTURES])(
		"%s: dependencies direct, devDependencies dev",
		async (name) => {
			const parsed = await parseFixture(fixture(name))
			expect(relationOf(parsed, "lodash")).toEqual(["direct"])
			expect(relationOf(parsed, "express")).toEqual(["direct"])
			expect(relationOf(parsed, "minimist")).toEqual(["dev"])
			expect(relationOf(parsed, "accepts")).toEqual(["transitive"])
			expect(parsed.packages.every((p) => p.ecosystem === "npm")).toBe(true)
		},
	)

	it.each(WORKSPACE_FIXTURES)("%s: workspace packages are not reported", async (name) => {
		const parsed = await parseFixture(fixture(name))
		expect(parsed.packages.filter((p) => p.name.startsWith("@fx/"))).toEqual([])
	})

	it.each(["yarn-v1/basic", "yarn-berry/basic"])(
		"%s: relations are unknown without manifests",
		async (name) => {
			const parsed = await parseFixture(fixture(name), false)
			expect(new Set(parsed.packages.map((p) => p.relation))).toEqual(new Set(["unknown"]))
			expect(parsed.warnings.some((w) => w.includes("package.json"))).toBe(true)
		},
	)

	it("detects berry from content and resolves its builtin patch entry to the npm version", async () => {
		const parsed = await parseFixture(fixture("yarn-berry/basic"))
		expect(parsed.kind).toBe("yarn-berry")
		expect(parsed.packages.filter((p) => p.name === "typescript")).toEqual([
			{ ecosystem: "npm", name: "typescript", version: "5.4.5", relation: "dev" },
		])
	})
})

describe("Cargo fixture", () => {
	it("marks the root crate's dependencies direct and skips the workspace member", async () => {
		const parsed = await parseFixture(fixture("cargo-lock/basic"))
		expect(relationOf(parsed, "time")).toEqual(["direct"])
		expect(relationOf(parsed, "h2")).toEqual(["direct"])
		expect(relationOf(parsed, "bytes")).toEqual(["transitive"])
		expect(relationOf(parsed, "fx")).toEqual([])
		expect(parsed.packages.every((p) => p.ecosystem === "crates.io")).toBe(true)
	})
})
