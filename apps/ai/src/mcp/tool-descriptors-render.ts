import type { McpToolDescriptor } from "@maple/domain/mcp-tool-contract"
import { Effect, Schema, Array as Arr, String as Str } from "effect"
import { codeUnitAt, replaceWith } from "@maple/strings"
import { loadRegistry } from "./tool-catalog"

const encodeJson = Schema.encodeSync(Schema.fromJsonString(Schema.Unknown))

/** JSON with every non-ASCII character escaped: the generated module stays plain ASCII. */
const asciiJson = (value: unknown): string =>
	replaceWith(
		encodeJson(value),
		/[\u0080-\uffff]/g,
		(char) => `\\u${Str.padStart(4, "0")(codeUnitAt(char, 0).toString(16))}`,
	)

/** The source of `tool-descriptors.generated.ts`: one tool per line, so a diff names the tool. */
export const renderToolDescriptorsModule = (descriptors: ReadonlyArray<McpToolDescriptor>): string =>
	Arr.join(
		[
			"// Generated by `bun run --cwd apps/ai mcp:tools` from the tool registry. Do not edit.",
			'import type { McpToolDescriptor } from "@maple/domain/mcp-tool-contract"',
			"",
			"export const MCP_TOOL_DESCRIPTORS: ReadonlyArray<McpToolDescriptor> = [",
			...Arr.map(descriptors, (descriptor) => `\t${asciiJson(descriptor)},`),
			"]",
			"",
		],
		"\n",
	)

const toolDescriptors = ({
	inputSchemaOf,
	mapleToolCatalogFor,
	toOutputSchema,
}: typeof import("./tools/registry")): ReadonlyArray<McpToolDescriptor> =>
	Arr.map(mapleToolCatalogFor("mcp"), (definition) => ({
		name: definition.name,
		// Current spec reads the top-level `title`; Claude's directory and older clients read `annotations.title`.
		title: definition.title,
		description: definition.description,
		inputSchema: inputSchemaOf(definition),
		...(definition.outputSchema === undefined
			? undefined
			: { outputSchema: toOutputSchema(definition.outputSchema) }),
		...(definition.hints === undefined
			? undefined
			: {
					annotations: {
						title: definition.title,
						readOnlyHint: definition.hints.readOnly,
						// The protocol defaults both of these to true; every Maple tool states them.
						destructiveHint: !definition.hints.readOnly && definition.hints.destructive === true,
						idempotentHint: definition.hints.readOnly || definition.hints.idempotent === true,
						openWorldHint: definition.hints.openWorld === true,
					},
				}),
	}))

/** The public transport's `tools/list`, built from the registry; the generator writes it out. */
export const listMcpTools = Effect.map(loadRegistry, toolDescriptors)

/** Where one callable name is defined, as the generator found it. */
export interface ToolModuleSource {
	readonly name: string
	readonly tool: string
	readonly title: string
	readonly audience: string
	readonly readOnly: boolean
	readonly permission: string | ReadonlyArray<string> | null
	/** The module under `src/mcp/tools`, without extension (`run-sql`). */
	readonly module: string
	/** Its registration function (`registerRunSqlTool`). */
	readonly register: string
}

/** The source of `tool-modules.generated.ts`: one name per line, each importing its own module. */
export const renderToolModulesModule = (sources: ReadonlyArray<ToolModuleSource>): string =>
	Arr.join(
		[
			"// Generated by `bun run --cwd apps/ai mcp:tools` from the tool registry. Do not edit.",
			'import type { McpToolModule } from "./tools/registry-core"',
			"",
			"/** Every tool name and retired alias, with the module that defines it, imported on first call. */",
			"export const MCP_TOOL_MODULES: ReadonlyArray<McpToolModule> = [",
			...Arr.map(
				sources,
				(source) =>
					`\t{ name: ${asciiJson(source.name)}, tool: ${asciiJson(source.tool)}, title: ${asciiJson(source.title)}, audience: ${asciiJson(source.audience)}, readOnly: ${source.readOnly ? "true" : "false"}, permission: ${source.permission === null ? "null" : asciiJson(source.permission)}, load: () => import(${asciiJson(`./tools/${source.module}`)}).then((module) => module.${source.register}) },`,
			),
			"]",
			"",
		],
		"\n",
	)
