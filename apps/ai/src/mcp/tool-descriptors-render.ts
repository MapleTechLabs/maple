import type { McpToolDescriptor } from "@maple/domain/mcp-tool-contract"
import { Schema } from "effect"

const encodeJson = Schema.encodeSync(Schema.fromJsonString(Schema.Unknown))

/** JSON with every non-ASCII character escaped: the generated module stays plain ASCII. */
const asciiJson = (value: unknown): string =>
	encodeJson(value).replace(
		/[^\x00-\x7f]/g,
		(char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`,
	)

/** The source of `tool-descriptors.generated.ts`: one tool per line, so a diff names the tool. */
export const renderToolDescriptorsModule = (descriptors: ReadonlyArray<McpToolDescriptor>): string =>
	[
		"// Generated by `bun run --cwd apps/ai mcp:tools` from the tool registry. Do not edit.",
		'import type { McpToolDescriptor } from "@maple/domain/mcp-tool-contract"',
		"",
		"export const MCP_TOOL_DESCRIPTORS: ReadonlyArray<McpToolDescriptor> = [",
		...descriptors.map((descriptor) => `\t${asciiJson(descriptor)},`),
		"]",
		"",
	].join("\n")
